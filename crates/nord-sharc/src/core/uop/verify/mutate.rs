//! Output-perturbation wrappers: they test the tests (design 4.6).
//!
//! OWNER: W1-VERIFY. `perturb(h, m)` returns a handler that calls `h` and, when `h` really ran
//! the uop (`Ok`, `Jump` or `Smc`: the store completed before `Smc`), changes one aspect of the
//! result: a data register bit, the hidden float extension, a flag, `stky`, `astat_extra`, a bit
//! FIFO bit, the circular-buffer latch, a stack slot, a SRAM word, the step count, the
//! multiplier result, a PEy register, a DAG register, an SDRAM word or a device word. A handler
//! is a bare `extern "C"` function pointer and cannot capture, so the wrapped handler lives in a
//! thread-local slot per mutant class (one wrapped handler per class per thread, which is all a
//! test needs) and one wrapper function per class is generated by a macro table.
//!
//! Every class changes the compared state in exactly the field [`Mutant::field`] names, from any
//! start state (a mutant that is a no-op for some state would let a real bug in that state
//! survive and would hide behind "mutant survived"): `HiddenLo` makes the extension live and
//! flips the effective byte, `StackSlot` flips or pushes, the rest flip a value.
//!
//! Obligation (W3-FUZZ): for every [`Mutant`], fuzz plus sweep plus comparator detect the mutant
//! within the default iteration count; a surviving mutant fails the suite.
use super::super::types::{Exit, Handler, Uop, UopCtx};
use crate::core::sdram;
use crate::core::Core;
use std::cell::Cell;

/// Number of mutant classes.
const N: usize = 15;
/// Device address the `DeviceWord` class writes. ASSUMED: any address that no peripheral model
/// owns reaches the sparse device store; `the_mutant_addresses_reach_the_device_store_and_the_sdram`
/// confirms this one lands in `Core::device` (a model that later claims it fails that test).
const DEVICE_ADDR: u32 = 0x3000_0040;
/// SDRAM word the `SdramWord` class flips. VERIFIED: `sdram::BASE + 0x10` lies in the SDRAM
/// window, checked by the same test (the write reads back through `Core::sdram`).
const SDRAM_ADDR: u32 = sdram::BASE + 0x10;

/// A class of wrong result.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Mutant {
    /// Flip bit 0 of data register `R0`.
    ResultBit = 0,
    /// Flip the effective float extension byte of `F0` (making it live).
    HiddenLo = 1,
    /// Toggle the `AZ` flag.
    Flag = 2,
    /// Flip a bit of the sticky register of PEx.
    Stky = 3,
    /// Flip a bit of the ASTAT extras of PEx.
    AstatExtra = 4,
    /// Flip a bit of the shifter bit FIFO.
    Fifo = 5,
    /// Flip the circular-buffer wrap latch.
    CbWrap = 6,
    /// Change the top call-stack slot (or push one).
    StackSlot = 7,
    /// Flip a SRAM byte.
    SramWord = 8,
    /// Add one to the step counter.
    StepCount = 9,
    /// Add one to the multiplier result `MRF`.
    MrResult = 10,
    /// Flip bit 0 of PEy data register `S0`.
    PeyResult = 11,
    /// Flip bit 0 of the DAG index register `I0`.
    DagReg = 12,
    /// Flip bit 0 of a word of the SDRAM delay-line window.
    SdramWord = 13,
    /// Flip bit 0 of a word of the sparse device store.
    DeviceWord = 14,
}

impl Mutant {
    /// Every class, in discriminant order.
    pub const ALL: [Mutant; N] = [
        Mutant::ResultBit,
        Mutant::HiddenLo,
        Mutant::Flag,
        Mutant::Stky,
        Mutant::AstatExtra,
        Mutant::Fifo,
        Mutant::CbWrap,
        Mutant::StackSlot,
        Mutant::SramWord,
        Mutant::StepCount,
        Mutant::MrResult,
        Mutant::PeyResult,
        Mutant::DagReg,
        Mutant::SdramWord,
        Mutant::DeviceWord,
    ];

    /// The `exact_diff` field this class must make differ.
    pub const fn field(self) -> &'static str {
        match self {
            Mutant::ResultBit => "r",
            Mutant::HiddenLo => "f40_x",
            Mutant::Flag => "flags",
            Mutant::Stky => "stky",
            Mutant::AstatExtra => "astat_extra",
            Mutant::Fifo => "fifo",
            Mutant::CbWrap => "cb_wrap",
            Mutant::StackSlot => "call_stack",
            Mutant::SramWord => "sram",
            Mutant::StepCount => "steps",
            Mutant::MrResult => "mr",
            Mutant::PeyResult => "s",
            Mutant::DagReg => "i",
            Mutant::SdramWord => "sdram",
            Mutant::DeviceWord => "device",
        }
    }

    /// Applies the wrong result to `c`.
    pub fn apply(self, c: &mut Core) {
        match self {
            Mutant::ResultBit => c.r[0] ^= 1,
            Mutant::HiddenLo => {
                let live = c.fx.tag[0] == c.r[0];
                let effective = if live { c.fx.lo[0] } else { 0 };
                c.fx.tag[0] = c.r[0];
                c.fx.lo[0] = effective ^ 1;
            }
            Mutant::Flag => c.flags.az = !c.flags.az,
            Mutant::Stky => c.sys.stky[0] ^= 1,
            Mutant::AstatExtra => c.sys.astat_extra[0] ^= 1,
            Mutant::Fifo => c.flags.fifo.bff ^= 1 << 63,
            Mutant::CbWrap => c.cb_wrap.set(c.cb_wrap.get() ^ 1),
            Mutant::StackSlot => match c.call_stack.last_mut() {
                Some(top) => *top ^= 1,
                None => c.call_stack.push(0xDEAD),
            },
            Mutant::SramWord => c.sram[0x40] ^= 1,
            Mutant::StepCount => c.steps += 1,
            Mutant::MrResult => c.mr[0] += 1,
            Mutant::PeyResult => c.s[0] ^= 1,
            Mutant::DagReg => c.i[0] ^= 1,
            Mutant::SdramWord => c.sdram.write(SDRAM_ADDR, c.sdram.read(SDRAM_ADDR) ^ 1),
            Mutant::DeviceWord => {
                let old = c.device.get(&DEVICE_ADDR).copied().unwrap_or(0);
                c.device.insert(DEVICE_ADDR, old ^ 1);
            }
        }
    }
}

thread_local! {
    /// The handler each mutant class wraps, per thread.
    static INNER: Cell<[Option<Handler>; N]> = const { Cell::new([None; N]) };
}

/// Whether an exit code means the uop ran and its effects are in the core.
fn ran(exit: u32) -> bool {
    exit == Exit::Ok as u32 || exit == Exit::Jump as u32 || exit == Exit::Smc as u32
}

macro_rules! wrappers {
    ($($idx:literal => $name:ident),* $(,)?) => {
        $(
            unsafe extern "C" fn $name(ctx: *mut UopCtx, u: *const Uop) -> u32 {
                let exit = match INNER.with(|t| t.get()[$idx]) {
                    Some(h) => h(ctx, u),
                    None => Exit::Slow as u32,
                };
                if ran(exit) {
                    Mutant::ALL[$idx].apply(&mut *(*ctx).core);
                }
                exit
            }
        )*
        const WRAPPERS: [Handler; N] = [$($name),*];
    };
}

wrappers! {
    0 => wrap_result_bit,
    1 => wrap_hidden_lo,
    2 => wrap_flag,
    3 => wrap_stky,
    4 => wrap_astat_extra,
    5 => wrap_fifo,
    6 => wrap_cb_wrap,
    7 => wrap_stack_slot,
    8 => wrap_sram_word,
    9 => wrap_step_count,
    10 => wrap_mr_result,
    11 => wrap_pey_result,
    12 => wrap_dag_reg,
    13 => wrap_sdram_word,
    14 => wrap_device_word,
}

/// A handler that calls `h` and then applies mutant `m` to the core. Wrapping twice with the same
/// class on one thread replaces the first handler.
pub fn perturb(h: Handler, m: Mutant) -> Handler {
    INNER.with(|t| {
        let mut a = t.get();
        a[m as usize] = Some(h);
        t.set(a);
    });
    WRAPPERS[m as usize]
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::uop::verify::compare::{exact_diff, FIELDS};
    use crate::core::uop::verify::gen::{
        fill_astat_extra, fill_fifo, fill_stacks, fill_state, fill_sticky, Rng,
    };
    use crate::core::uop::verify::snap::CoreSnap;

    /// A handler that does nothing and succeeds.
    unsafe extern "C" fn ok_handler(_ctx: *mut UopCtx, _u: *const Uop) -> u32 {
        Exit::Ok as u32
    }

    fn run(h: Handler, c: &mut Core) -> u32 {
        let mut ctx = UopCtx::new(c as *mut Core, c.steps, 8);
        let u = Uop::default();
        // SAFETY: `ctx.core` points to `c`, which outlives the call; the handlers only touch it.
        unsafe { h(&mut ctx, &u) }
    }

    /// A start state with every kind of hidden state, from one seed; `stack` sets the call depth.
    fn start(seed: u64, stack: usize) -> Core {
        let mut c = Core::new(&[]);
        let mut rng = Rng::new(seed);
        fill_state(&mut c, &mut rng, seed.is_multiple_of(2));
        fill_sticky(&mut c, &mut rng);
        fill_astat_extra(&mut c, &mut rng);
        fill_fifo(&mut c, &mut rng);
        fill_stacks(&mut c, &mut rng, stack, 1);
        c.dm_write(DEVICE_ADDR, rng.next_u32()).unwrap();
        c.dm_write(SDRAM_ADDR, rng.next_u32()).unwrap();
        c
    }

    thread_local! {
        /// The exit code `exit_with` returns.
        static EXIT: Cell<u32> = const { Cell::new(0) };
    }

    /// A handler that returns the exit code in `EXIT` without touching the core.
    unsafe extern "C" fn exit_with(_ctx: *mut UopCtx, _u: *const Uop) -> u32 {
        EXIT.with(Cell::get)
    }

    /// Forgets every wrapped handler of this thread (tests may share a thread).
    fn reset() {
        INNER.with(|t| t.set([None; N]));
    }

    #[test]
    fn every_class_trips_the_field_it_names_and_only_that_one() {
        for m in Mutant::ALL {
            assert!(FIELDS.contains(&m.field()), "{m:?}");
            let (mut a, b) = (Core::new(&[]), Core::new(&[]));
            assert_eq!(run(perturb(ok_handler, m), &mut a), Exit::Ok as u32);
            let d = exact_diff(&a, &b).unwrap_or_else(|| panic!("{m:?} not detected"));
            assert_eq!(d.field, m.field(), "{m:?}: {d}");
        }
    }

    #[test]
    fn every_class_is_detected_from_any_start_state_and_changes_nothing_else() {
        for m in Mutant::ALL {
            for seed in 1..16u64 {
                for stack in [0, 3] {
                    let (mut a, b) = (start(seed, stack), start(seed, stack));
                    assert_eq!(exact_diff(&a, &b), None, "the two starts differ");
                    run(perturb(ok_handler, m), &mut a);
                    let d = exact_diff(&a, &b)
                        .unwrap_or_else(|| panic!("{m:?} a no-op (seed {seed}, stack {stack})"));
                    assert_eq!(d.field, m.field(), "{m:?} (seed {seed}): {d}");
                    // restoring everything the snapshot holds leaves only a SRAM change, which the
                    // snapshot (by design) does not hold
                    CoreSnap::capture(&b).restore(&mut a);
                    let left = exact_diff(&a, &b).map(|d| d.field);
                    let want = (m == Mutant::SramWord).then_some("sram");
                    assert_eq!(left, want, "{m:?} changed something it does not name");
                }
            }
        }
    }

    #[test]
    fn hidden_lo_changes_the_effective_byte_whatever_the_extension_was() {
        // a stale extension with lo = 1 reads as zero; a mutant that only made it live and
        // flipped lo would write 0, which also reads as zero: a no-op for exactly this state
        let make = |tag: u32, lo: u8| {
            let mut c = Core::new(&[]);
            c.r[0] = 0x3F80_0000;
            c.fx.tag[0] = tag;
            c.fx.lo[0] = lo;
            c
        };
        let (mut stale, same) = (make(0x1234, 1), make(0x1234, 1));
        assert_eq!(exact_diff(&stale, &same), None);
        run(perturb(ok_handler, Mutant::HiddenLo), &mut stale);
        assert_eq!(exact_diff(&stale, &same).map(|d| d.field), Some("f40_x"));
        assert_eq!((stale.fx.tag[0], stale.fx.lo[0]), (0x3F80_0000, 1));
        // a live extension is flipped in place
        let (mut live, same) = (make(0x3F80_0000, 0xAB), make(0x3F80_0000, 0xAB));
        run(perturb(ok_handler, Mutant::HiddenLo), &mut live);
        assert_eq!(live.fx.lo[0], 0xAA);
        assert_eq!(exact_diff(&live, &same).map(|d| d.field), Some("f40_x"));
    }

    #[test]
    fn a_handler_that_did_not_run_the_uop_is_not_perturbed() {
        for exit in [Exit::Fault, Exit::Guard, Exit::Slow] {
            EXIT.with(|e| e.set(exit as u32));
            let (mut a, b) = (Core::new(&[]), Core::new(&[]));
            let h = perturb(exit_with, Mutant::StepCount);
            assert_eq!(run(h, &mut a), exit as u32);
            assert_eq!(exact_diff(&a, &b), None, "{exit:?}");
        }
    }

    #[test]
    fn a_uop_that_ran_is_perturbed_whatever_the_exit_that_says_so() {
        for exit in [Exit::Ok, Exit::Jump, Exit::Smc] {
            EXIT.with(|e| e.set(exit as u32));
            let (mut a, b) = (Core::new(&[]), Core::new(&[]));
            assert_eq!(run(perturb(exit_with, Mutant::Flag), &mut a), exit as u32);
            assert_eq!(
                exact_diff(&a, &b).map(|d| d.field),
                Some("flags"),
                "{exit:?}"
            );
        }
    }

    #[test]
    fn a_class_without_a_wrapped_handler_declines_and_a_second_wrap_replaces_the_first() {
        reset();
        let (mut a, b) = (Core::new(&[]), Core::new(&[]));
        // the wrapper of a class nobody wrapped on this thread: Slow, and no mutation
        assert_eq!(
            run(WRAPPERS[Mutant::CbWrap as usize], &mut a),
            Exit::Slow as u32
        );
        assert_eq!(exact_diff(&a, &b), None);
        perturb(ok_handler, Mutant::CbWrap);
        EXIT.with(|e| e.set(Exit::Slow as u32));
        let h = perturb(exit_with, Mutant::CbWrap);
        assert_eq!(run(h, &mut a), Exit::Slow as u32, "the second handler won");
        assert_eq!(exact_diff(&a, &b), None);
    }

    #[test]
    fn the_mutant_addresses_reach_the_device_store_and_the_sdram() {
        let mut c = Core::new(&[]);
        c.dm_write(DEVICE_ADDR, 0x1234_5678).unwrap();
        c.dm_write(SDRAM_ADDR, 0x9ABC_DEF0).unwrap();
        assert_eq!(c.device.get(&DEVICE_ADDR), Some(&0x1234_5678));
        assert_eq!(c.sdram.read(SDRAM_ADDR), 0x9ABC_DEF0);
    }

    #[test]
    fn classes_are_numbered_in_table_order_and_each_has_its_own_wrapper() {
        for (k, m) in Mutant::ALL.iter().enumerate() {
            assert_eq!(*m as usize, k);
        }
        let mut names: Vec<_> = Mutant::ALL.iter().map(|m| m.field()).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), N, "every class names a field of its own");
        let mut ptrs: Vec<usize> = WRAPPERS.iter().map(|h| *h as usize).collect();
        ptrs.sort_unstable();
        ptrs.dedup();
        assert_eq!(ptrs.len(), N, "one wrapper function per class");
    }
}

//! Output-perturbation wrappers: they test the tests (design 4.6).
//!
//! OWNER: W1-VERIFY. `perturb(h, m)` returns a handler that calls `h` and, when `h` really ran
//! the uop (`Ok` or `Jump`), changes one aspect of the result: a data register bit, the hidden
//! float extension, a flag, `stky`, `astat_extra`, a bit FIFO bit, the circular-buffer latch, a
//! stack slot, a SRAM word or the step count. A handler is a bare `extern "C"` function pointer
//! and cannot capture, so the wrapped handler lives in a thread-local slot per mutant class (one
//! wrapped handler per class per thread, which is all a test needs) and one wrapper function per
//! class is generated by a macro table.
//!
//! Obligation (W3-FUZZ): for every [`Mutant`], fuzz plus sweep plus comparator detect the mutant
//! within the default iteration count; a surviving mutant fails the suite.
//!
//! Skeleton: complete; `Mutant::field` names the `exact_diff` field each class must trip.
use super::super::types::{Exit, Handler, Uop, UopCtx};
use crate::core::Core;
use std::cell::Cell;

/// A class of wrong result.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Mutant {
    /// Flip bit 0 of data register `R0`.
    ResultBit = 0,
    /// Flip the float extension byte of `F0` (and make it live).
    HiddenLo = 1,
    /// Set the `AZ` flag.
    Flag = 2,
    /// Flip a bit of the sticky register of PEx.
    Stky = 3,
    /// Flip a bit of the ASTAT extras of PEx.
    AstatExtra = 4,
    /// Flip a bit of the shifter bit FIFO.
    Fifo = 5,
    /// Flip the circular-buffer wrap latch.
    CbWrap = 6,
    /// Change the top call-stack slot (or push one).
    StackSlot = 7,
    /// Flip a SRAM byte.
    SramWord = 8,
    /// Add one to the step counter.
    StepCount = 9,
}

impl Mutant {
    /// Every class, in discriminant order.
    pub const ALL: [Mutant; 10] = [
        Mutant::ResultBit,
        Mutant::HiddenLo,
        Mutant::Flag,
        Mutant::Stky,
        Mutant::AstatExtra,
        Mutant::Fifo,
        Mutant::CbWrap,
        Mutant::StackSlot,
        Mutant::SramWord,
        Mutant::StepCount,
    ];

    /// The `exact_diff` field this class must make differ.
    pub const fn field(self) -> &'static str {
        match self {
            Mutant::ResultBit => "r",
            Mutant::HiddenLo => "f40_x",
            Mutant::Flag => "flags",
            Mutant::Stky => "stky",
            Mutant::AstatExtra => "astat_extra",
            Mutant::Fifo => "fifo",
            Mutant::CbWrap => "cb_wrap",
            Mutant::StackSlot => "call_stack",
            Mutant::SramWord => "sram",
            Mutant::StepCount => "steps",
        }
    }

    /// Applies the wrong result to `c`.
    pub fn apply(self, c: &mut Core) {
        match self {
            Mutant::ResultBit => c.r[0] ^= 1,
            Mutant::HiddenLo => {
                c.fx.tag[0] = c.r[0];
                c.fx.lo[0] ^= 1;
            }
            Mutant::Flag => c.flags.az = !c.flags.az,
            Mutant::Stky => c.sys.stky[0] ^= 1,
            Mutant::AstatExtra => c.sys.astat_extra[0] ^= 1,
            Mutant::Fifo => c.flags.fifo.bff ^= 1 << 63,
            Mutant::CbWrap => c.cb_wrap.set(c.cb_wrap.get() ^ 1),
            Mutant::StackSlot => match c.call_stack.last_mut() {
                Some(top) => *top ^= 1,
                None => c.call_stack.push(0xDEAD),
            },
            Mutant::SramWord => c.sram[0x40] ^= 1,
            Mutant::StepCount => c.steps += 1,
        }
    }
}

thread_local! {
    /// The handler each mutant class wraps, per thread.
    static INNER: Cell<[Option<Handler>; 10]> = const { Cell::new([None; 10]) };
}

macro_rules! wrappers {
    ($($idx:literal => $name:ident),* $(,)?) => {
        $(
            unsafe extern "C" fn $name(ctx: *mut UopCtx, u: *const Uop) -> u32 {
                let exit = match INNER.with(|t| t.get()[$idx]) {
                    Some(h) => h(ctx, u),
                    None => Exit::Slow as u32,
                };
                if exit == Exit::Ok as u32 || exit == Exit::Jump as u32 {
                    Mutant::ALL[$idx].apply(&mut *(*ctx).core);
                }
                exit
            }
        )*
        const WRAPPERS: [Handler; 10] = [$($name),*];
    };
}

wrappers! {
    0 => wrap_result_bit,
    1 => wrap_hidden_lo,
    2 => wrap_flag,
    3 => wrap_stky,
    4 => wrap_astat_extra,
    5 => wrap_fifo,
    6 => wrap_cb_wrap,
    7 => wrap_stack_slot,
    8 => wrap_sram_word,
    9 => wrap_step_count,
}

/// A handler that calls `h` and then applies mutant `m` to the core. Wrapping twice with the same
/// class on one thread replaces the first handler.
pub fn perturb(h: Handler, m: Mutant) -> Handler {
    INNER.with(|t| {
        let mut a = t.get();
        a[m as usize] = Some(h);
        t.set(a);
    });
    WRAPPERS[m as usize]
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::uop::verify::compare::{exact_diff, FIELDS};

    /// A handler that does nothing and succeeds.
    unsafe extern "C" fn ok_handler(_ctx: *mut UopCtx, _u: *const Uop) -> u32 {
        Exit::Ok as u32
    }

    fn run(h: Handler, c: &mut Core) -> u32 {
        let mut ctx = UopCtx::new(c as *mut Core, c.steps, 8);
        let u = Uop::default();
        // SAFETY: `ctx.core` points to `c`, which outlives the call; the handlers only touch it.
        unsafe { h(&mut ctx, &u) }
    }

    #[test]
    fn every_class_trips_the_field_it_names_and_only_that_one() {
        for m in Mutant::ALL {
            assert!(FIELDS.contains(&m.field()), "{m:?}");
            let (mut a, b) = (Core::new(&[]), Core::new(&[]));
            assert_eq!(run(perturb(ok_handler, m), &mut a), Exit::Ok as u32);
            let d = exact_diff(&a, &b).unwrap_or_else(|| panic!("{m:?} not detected"));
            assert_eq!(d.field, m.field(), "{m:?}: {d}");
        }
    }

    #[test]
    fn a_handler_that_did_not_run_the_uop_is_not_perturbed() {
        unsafe extern "C" fn slow(_ctx: *mut UopCtx, _u: *const Uop) -> u32 {
            Exit::Slow as u32
        }
        let (mut a, b) = (Core::new(&[]), Core::new(&[]));
        assert_eq!(
            run(perturb(slow, Mutant::StepCount), &mut a),
            Exit::Slow as u32
        );
        assert_eq!(exact_diff(&a, &b), None);
    }

    #[test]
    fn classes_are_numbered_in_table_order() {
        for (k, m) in Mutant::ALL.iter().enumerate() {
            assert_eq!(*m as usize, k);
        }
    }
}

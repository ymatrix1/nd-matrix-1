//! Piano timbre (`Edt_Pno_kEq`) as the firmware plays it: a per-note gain, opt-in.
//!
//! Evidence: `docs/research/piano-timbre-gain.md`. The `kEq` handler `0xC011EC2C` maps the edit value to a
//! timbre **mode** (by sound family) and the voice-frame builder `0xC00AA520` turns the modes `0x10..=0x1A`
//! into one gain per note, no filter involved. With `r2 = mode - 0x10`, the played `key` and
//! `sl = r8 >> 3` (`r8` = internal velocity, [`R8`]):
//!
//! ```text
//! idx = key + 128 r2
//! n   = ((S[sl + 128 r2] * T1[idx] + T2[idx]) * 10) >> 16        (floor, n < 0 reads 0)
//! amp = G[n] >> 2                    for n <= 60
//! amp = G[n - 60 k] >> (k + 2)       for n > 60
//! ```
//!
//! `G` is the level table ([`super::level_q23`]); `amp` is the Q23 voice gain, `0x200000` (unity, float word
//! `0.25`) when no timbre applies. One `n` step is 0.1003 dB, so the timbre only ever attenuates.
//!
//! VERIFIED: the model equals the gain word the real firmware sends for a new voice in 99 of 99 runs of
//! `tools/arm_piano_timbre.py` (11 modes x keys 24, 60, 96 x velocities 30, 80, 127, Clavinet D6 loaded,
//! mode forced at `[[core + 0x390] + 0x58]`; `tools/piano_timbre_gain.py check`, test
//! `matches_the_arm_oracle_cases`). The tables are the firmware ROM (`0xC02A1D94`, `0xC02A3394`,
//! `0xC02A4994`; generated by `tools/piano_timbre_gain.py rust`).
//!
//! ASSUMED: the key is the played key (no octave shift), the flag at `0xC059868C + 0x904` is 0 (the other
//! branch of the builder is not modelled), and sounding voices keep the gain they started with (the
//! firmware retargets them with a single-velocity approximation when the timbre changes, not modelled).

use super::level_q23::{level_table, Q23_MAX};
use super::timbre_gain_tables::{R8, S, T1, T2};
use super::{PianoLayer, PianoTimbre};

/// First mode with gain tables (`kEq` family modes `0x10..=0x1A`).
pub const FIRST_MODE: u8 = 0x10;
/// Number of modes with tables.
pub const MODE_COUNT: usize = 11;
/// Q23 gain with no timbre (`0.25` as the float word of the SMP voice record).
pub const UNITY_Q23: u32 = 0x20_0000;

/// Internal velocity `r8` of a MIDI velocity (curve 6, VERIFIED, `tools/arm_touch_curves.py`); 0 maps to 1.
pub fn internal_velocity(velocity: u8) -> u16 {
    R8[usize::from(velocity.clamp(1, 127)) - 1]
}

/// Attenuation index `n` (steps of 0.1003 dB) of `mode` at `key` for the velocity argument `sl`; `None`
/// for a mode without tables.
pub fn attenuation_index(mode: u8, key: u8, sl: u16) -> Option<u32> {
    let r2 = usize::from(mode.checked_sub(FIRST_MODE)?);
    if r2 >= MODE_COUNT {
        return None;
    }
    let sl = usize::from(sl).min(127);
    let idx = usize::from(key.min(127)) + 128 * r2;
    let raw = (i64::from(S[sl + 128 * r2]) * i64::from(T1[idx]) + i64::from(T2[idx])) * 10;
    Some((raw >> 16).max(0) as u32)
}

/// Q23 voice gain of `mode` for `key` and `velocity` (`UNITY_Q23` for a mode without tables).
pub fn amp_q23(mode: u8, key: u8, velocity: u8) -> u32 {
    let sl = internal_velocity(velocity) >> 3;
    let Some(mut n) = attenuation_index(mode, key, sl) else {
        return UNITY_Q23;
    };
    // The ROM table holds `0x7FFFFF` for index 0 (the closed form gives `0x800000`).
    let g = level_table();
    if n <= 60 {
        return g[n as usize].min(Q23_MAX) >> 2;
    }
    let mut k = 0;
    while n > 60 {
        n -= 60;
        k += 1;
    }
    g[n as usize].min(Q23_MAX) >> (k + 2)
}

/// Linear gain of the timbre against no timbre, `<= 1`.
pub fn gain(mode: u8, key: u8, velocity: u8) -> f32 {
    amp_q23(mode, key, velocity) as f32 / UNITY_Q23 as f32
}

/// The `kEq` edit value of an engine timbre (`Edt_Pno_kEq`, 0..=5; the Clav masks 6 and 7 collapse to `Bright`).
pub fn raw_of(timbre: PianoTimbre) -> u8 {
    match timbre {
        PianoTimbre::Off => 0,
        PianoTimbre::Soft => 1,
        PianoTimbre::Mid => 2,
        PianoTimbre::Bright => 3,
        PianoTimbre::Dyno1 => 4,
        PianoTimbre::Dyno2 => 5,
    }
}

/// Timbre mode the firmware stores for the edit value `raw` on a sound of file class `class` (`.npno` byte
/// `0x44`; `None` for a sound without a level model, which takes the generic path), `None` when the mode has
/// no gain tables (mode 0, or a mode below `0x10`).
///
/// VERIFIED: the table is the control flow of the handler `0xC011EC2C` / `0xC00B281C`, read from the code
/// and run for the generic path (`kEq` 0..=7 gave `0, 0x10, 0x11, 0x12, 0, 0x10, 0x11, 0x12`).
/// EMPIRICAL: the family of the Electric classes 2 and 3 depends on a sound field (`[sound + 0x64B8] > 5`: five
/// modes `0x13..=0x17`, else three) that is not decoded; the five-mode table is used (the two agree for
/// `raw <= 3`). The Clav class 4 stores `0, 1, 4, 5, 8, 9, 0xC, 0xF` (modes without gain tables: `None`).
pub fn mode_for_class(class: Option<u8>, raw: u8) -> Option<u8> {
    match class {
        Some(4) => None,
        Some(2 | 3) => match raw % 6 {
            r @ 1..=5 => Some(0x12 + r),
            _ => None,
        },
        _ => match raw & 3 {
            1 if matches!(class, Some(5 | 6)) => Some(0x19),
            1 => Some(0x10),
            2 => Some(0x11),
            3 => Some(0x12),
            _ => None,
        },
    }
}

impl PianoLayer {
    /// The timbre mode whose firmware gain tables apply to this layer, `None` when the opt-in is off or the
    /// timbre keeps the engine contour.
    pub(super) fn firmware_timbre_mode(&self) -> Option<u8> {
        if !self.firmware_timbre_gain {
            return None;
        }
        let class = self
            .sound
            .as_ref()
            .and_then(|sound| sound.firmware_level.as_ref())
            .map(|model| model.class());
        mode_for_class(class, raw_of(self.timbre))
    }

    /// Gain factor of the firmware timbre for a note start (`1.0` when it does not apply).
    pub(super) fn firmware_timbre_factor(&self, note: u8, velocity: u8) -> f32 {
        self.firmware_timbre_mode()
            .map_or(1.0, |mode| gain(mode, note, velocity))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[derive(serde::Deserialize)]
    struct Case {
        mode: u8,
        key: u8,
        velocity: u8,
        r8: u16,
        word: u32,
    }

    #[derive(serde::Deserialize)]
    struct Cases {
        cases: Vec<Case>,
    }

    fn float_word(amp: u32) -> u32 {
        (amp as f32 / 8_388_608.0).to_bits()
    }

    #[test]
    fn matches_the_arm_oracle_cases() {
        let data: Cases = serde_json::from_str(include_str!(
            "../../../../docs/research/data/piano-timbre-gain-cases.json"
        ))
        .unwrap();
        assert_eq!(data.cases.len(), 108);
        for c in &data.cases {
            assert_eq!(
                internal_velocity(c.velocity),
                c.r8,
                "r8 of velocity {}",
                c.velocity
            );
            assert_eq!(
                float_word(amp_q23(c.mode, c.key, c.velocity)),
                c.word,
                "mode {:#x} key {} velocity {}",
                c.mode,
                c.key,
                c.velocity
            );
        }
    }

    #[test]
    fn no_timbre_and_unknown_modes_are_unity() {
        assert_eq!(amp_q23(0, 60, 100), UNITY_Q23);
        assert_eq!(amp_q23(0x0F, 60, 100), UNITY_Q23);
        assert_eq!(amp_q23(0x1B, 60, 100), UNITY_Q23);
        assert_eq!(float_word(UNITY_Q23), 0x3E80_0000);
        assert_eq!(attenuation_index(0x0F, 60, 10), None);
    }

    #[test]
    fn the_timbre_only_attenuates_and_stays_bounded() {
        for mode in FIRST_MODE..FIRST_MODE + MODE_COUNT as u8 {
            for key in (0..=127).step_by(7) {
                for velocity in (1..=127).step_by(9) {
                    let g = gain(mode, key, velocity);
                    assert!(
                        (0.0..=1.0).contains(&g),
                        "mode {mode:#x} key {key} vel {velocity}: {g}"
                    );
                }
            }
        }
    }

    #[test]
    fn mode_0x10_is_flat_six_db_at_low_velocity_and_tilts_with_velocity() {
        // n = 60 (one octave, -6.02 dB) where S is 0 (velocities up to about 40), then key dependent.
        assert_eq!(attenuation_index(0x10, 36, 10), Some(60));
        assert_eq!(attenuation_index(0x10, 100, 10), Some(60));
        let low = attenuation_index(0x10, 24, 80).unwrap();
        let high = attenuation_index(0x10, 100, 80).unwrap();
        assert!(high < low, "high keys lose less at forte: {high} < {low}");
    }

    #[test]
    fn internal_velocity_is_the_curve_6_table() {
        assert_eq!(internal_velocity(1), 17);
        assert_eq!(internal_velocity(64), 203);
        assert_eq!(internal_velocity(127), 656);
        assert_eq!(internal_velocity(0), 17, "velocity 0 reads as 1");
    }

    #[test]
    fn mode_map_follows_the_family_of_the_sound() {
        assert_eq!(raw_of(PianoTimbre::Dyno2), 5);
        let generic: Vec<_> = (0..8).map(|r| mode_for_class(None, r)).collect();
        assert_eq!(
            generic,
            [
                None,
                Some(0x10),
                Some(0x11),
                Some(0x12),
                None,
                Some(0x10),
                Some(0x11),
                Some(0x12)
            ]
        );
        assert_eq!(mode_for_class(Some(5), 1), Some(0x19));
        assert_eq!(mode_for_class(Some(6), 1), Some(0x19));
        assert_eq!(mode_for_class(Some(1), 1), Some(0x10));
        assert_eq!(mode_for_class(Some(2), 1), Some(0x13));
        assert_eq!(mode_for_class(Some(3), 5), Some(0x17));
        assert_eq!(mode_for_class(Some(2), 0), None);
        assert_eq!(
            mode_for_class(Some(4), 3),
            None,
            "Clav modes have no gain tables"
        );
    }

    #[test]
    fn layer_applies_the_gain_only_when_opted_in() {
        let mut layer = PianoLayer::new(48_000.0);
        layer.timbre = PianoTimbre::Soft;
        assert_eq!(layer.firmware_timbre_factor(60, 100), 1.0, "default off");
        layer.firmware_timbre_gain = true;
        let soft = layer.firmware_timbre_factor(60, 100);
        assert!(soft < 1.0 && soft > 0.4, "{soft}");
        assert_eq!(soft, gain(0x10, 60, 100));
        layer.timbre = PianoTimbre::Off;
        assert_eq!(layer.firmware_timbre_factor(60, 100), 1.0);
        assert_eq!(layer.firmware_timbre_mode(), None);
    }
}

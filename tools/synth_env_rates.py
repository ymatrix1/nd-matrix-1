def rust_words(name: str, words: list[int]) -> str:
    lines = [f"pub(super) const {name}: [u32; {len(words)}] = ["]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"{w:#010x}" for w in words[i : i + 8]) + ",")
    return chr(10).join(lines) + chr(10) + "];" + chr(10)


def emit(ns: argparse.Namespace) -> int:  # pragma: no cover - CLI wiring
    rows = list(csv.DictReader(Path(ns.settled).open(encoding="utf-8")))
    att = [int(r["attack_bits"], 16) for r in rows]
    dec = [int(r["decay_bits"], 16) for r in rows]
    sys.stdout.write(
        RUST_HEADER
        + rust_words("ATTACK_BITS", att)
        + rust_words("DECAY_BITS", dec)
        + RUST_TAIL
        + RUST_TESTS
    )
    return 0


BUCKET = 16  # index range width of the census


def bucket(index: int) -> int:
    """Lower end of the 16 wide index range of an index (-64, -48, ..., 48; 64 alone)."""
    return -64 + BUCKET * ((index + 64) // BUCKET)


def stale_indexes(settled: list[dict], old: list[dict], decay: bool, tol: float = 0.02) -> set[int]:
    """Indexes where the stale sweep differs from the settled value by more than `tol`.

    `decay` compares `1 - a` (the rate), else the attack coefficient. Rows are CSV dict rows of
    the settled file and of `synth-env-rate-table.csv`, in index order.
    """
    new_col, old_col = ("decay_coeff", "decay_release_coeff") if decay else ("attack_coeff",) * 2
    out = set()
    for n, o in zip(settled, old, strict=True):
        if abs(rate_ratio(float(n[new_col]), float(o[old_col]), decay) - 1.0) > tol:
            out.add(int(n["index"]))
    return out


def census(rows: list[dict], stale_attack: set[int], stale_decay: set[int]) -> dict:
    """Counts of the layer rows of `synth_env_census` per envelope, parameter and index range.

    Returns `{"layers": n, "programs": n, "ranges": {"amp.attack": {lo: layers}, ...},
    "stale_layers": n, "stale_programs": n}`; a layer is stale when any of its six indexes lands
    on an index where the stale sweep is off by more than 2 % (attack: attack table, decay and
    release: decay table).
    """
    ranges: dict[str, dict[int, int]] = {}
    stale_progs: set[str] = set()
    stale_layers = entries = stale_entries = 0
    progs: set[str] = set()
    n = 0
    for r in rows:
        if "program" not in r:
            continue
        n += 1
        progs.add(r["program"])
        hit = False
        for env in ("amp", "filter"):
            for par in ("attack", "decay", "release"):
                idx = int(r[env][par])
                d = ranges.setdefault(f"{env}.{par}", {})
                d[bucket(idx)] = d.get(bucket(idx), 0) + 1
                bad = idx in (stale_attack if par == "attack" else stale_decay)
                entries += 1
                stale_entries += bad
                hit |= bad
        if hit:
            stale_layers += 1
            stale_progs.add(r["program"])
    return {
        "layers": n,
        "programs": len(progs),
        "ranges": ranges,
        "entries": entries,
        "stale_entries": stale_entries,
        "stale_layers": stale_layers,
        "stale_programs": len(stale_progs),
    }


def census_cmd(ns: argparse.Namespace) -> int:  # pragma: no cover - CLI wiring
    import json

    rows = [json.loads(x) for x in Path(ns.jsonl).read_text(encoding="utf-8").splitlines()]
    new = list(csv.DictReader(Path(ns.settled).open(encoding="utf-8")))
    old = list(csv.DictReader(Path(t.RATE_TABLE).open(encoding="utf-8")))
    res = census(rows, stale_indexes(new, old, False), stale_indexes(new, old, True))
    print(json.dumps(res, indent=1, sort_keys=True))
    return 0


def plateaus(values: list[float]) -> int:
    """Number of indexes whose value equals the previous index's value."""
    return sum(1 for a, b in zip(values, values[1:], strict=False) if a == b)


def rate_ratio(new: float, old: float, decay: bool) -> float:
    """New over old rate: the attack coefficient, or `1 - a` for a decay / release coefficient."""
    return (1.0 - new) / (1.0 - old) if decay else new / old


def compare(ns: argparse.Namespace) -> int:  # pragma: no cover - CLI wiring
    new = list(csv.DictReader(Path(ns.settled).open(encoding="utf-8")))
    old = list(csv.DictReader(Path(t.RATE_TABLE).open(encoding="utf-8")))
    for col_new, col_old, decay in (
        ("attack_coeff", "attack_coeff", False),
        ("decay_coeff", "decay_release_coeff", True),
    ):
        ratios = [
            rate_ratio(float(n[col_new]), float(o[col_old]), decay)
            for n, o in zip(new, old, strict=True)
        ]
        off = sum(1 for r in ratios if abs(r - 1) > 0.02)
        print(
            f"{col_new}: {off}/{len(ratios)} indexes differ >2%; "
            f"ratio range {min(ratios):.3g}..{max(ratios):.3g}"
        )
    same = sum(1 for n in new if n["decay_coeff"] == n["release_coeff"])
    print(f"decay == release at {same}/{len(new)} indexes")
    return 0


def main(argv: list[str] | None = None) -> int:  # pragma: no cover - CLI wiring
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sweep")
    s.add_argument("--sharc-sys", required=True)
    s.add_argument("--image", required=True)
    s.add_argument("--load", required=True, help="core 2 load.script (synth_e2e_oracle)")
    s.add_argument("--workdir", default="target/synth_env_rates")
    s.add_argument("--out", required=True)
    s.add_argument("--passes", type=int, default=64)
    s.add_argument("--settle", type=int, default=2 * APPLY_PERIOD)
    c = sub.add_parser("compare")
    c.add_argument("settled")
    e = sub.add_parser("emit")
    e.add_argument("settled")
    k = sub.add_parser("census")
    k.add_argument("jsonl", help="output of the synth_env_census binary")
    k.add_argument("settled")
    ns = ap.parse_args(argv)
    return {"sweep": sweep, "compare": compare, "emit": emit, "census": census_cmd}[ns.cmd](ns)


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
# ruff: noqa: E501
r"""Settled envelope rate tables of the ORG core 2 oracle (D212).

The installer of the core 2 pass (`0x12720F..0x127281`) turns each ADR strip word into a per-pass
coefficient and stores it at `DM(0xC0E21..)` only on the apply pass, every 16th pass. The old
sweep (`synth-env-rate-table.csv`, D130) read 3 passes after each poke and so saw the previous
index's value over 5 or 6 indexes. This tool pokes the three amp ADR words (attack, decay,
release) with one index at pass 0, runs `--passes` passes, taps the nine installer outputs every
pass and keeps the value of the last pass after checking that it did not change over the last
`--settle` passes. One run (about 0.3 s) per index.

    uv run python tools/synth_env_rates.py sweep --sharc-sys target/release/sharc-sys \
        --image DIR/core2_sram.bin --load LOAD.script --out docs/research/data/synth-env-rates-settled.csv
    uv run python tools/synth_env_rates.py compare docs/research/data/synth-env-rates-settled.csv
"""

from __future__ import annotations

import argparse
import csv
import struct
import subprocess
import sys
from pathlib import Path

import numpy as np
import synth_env_trace as t

# VERIFIED (synth-stage-equations s7): installer output words, amp A/D/R, filter A/D/R, osc A/D/R.
COEF_TAPS = (
    0xC0E21, 0xC0E24, 0xC0E28, 0xC0E35, 0xC0E38, 0xC0E3C, 0xC0E41, 0xC0E44, 0xC0E48,
)  # fmt: skip
FIELDS = ("index", "attack_coeff", "decay_coeff", "release_coeff", "attack_bits", "decay_bits")
INDEX_RANGE = range(-64, 65)
APPLY_PERIOD = 16  # the installer rewrites the coefficients every 16th pass


def f32_to_bits(x: float) -> int:
    return struct.unpack("<I", struct.pack("<f", x))[0]


def index_words(index: int) -> dict[int, int]:
    """The nine ADR words with one index (top byte), as the ARM writes them."""
    return {t.ADR_BASE + i: (index << 24) & 0xFFFFFFFF for i in range(9)}


def settled_row(trace: np.ndarray, settle: int) -> np.ndarray:
    """Last row of a `[passes, taps]` trace; raises when it moved in the last `settle` passes."""
    tail = trace[-settle:]
    if not (tail == tail[-1]).all():
        raise ValueError(f"coefficients still moving in the last {settle} passes")
    return trace[-1]


def check_chains(row: np.ndarray) -> None:
    """The three chains get the same table: A/D/R coefficients must agree across amp/filter/osc."""
    for k in range(3):
        for c in (row[k::3],):
            if not (c == c[0]).all():
                raise ValueError(f"chains disagree: {row}")


def run_index(
    ns: argparse.Namespace, index: int, work: Path, passes: int, settle: int
) -> dict[str, float]:
    script = work / f"idx_{index}.script"
    script.write_text(t.inject_script(index_words(index)))
    out = work / f"idx_{index}.bin"
    cmd = [ns.sharc_sys, ns.image, "--passes", str(passes), "--warmup", "0", "--epdma"]
    cmd += ["--script-flat", ns.load, "--script-at", f"0:{script}"]
    for a in COEF_TAPS:
        cmd += ["--tap", f"{a:#x}:1"]
    cmd += ["--tap-out", str(out)]
    r = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if "tap:" not in r.stdout:
        raise RuntimeError(r.stdout[-600:] + r.stderr[-300:])
    raw = np.fromfile(out, dtype="<u4").reshape(-1, len(COEF_TAPS))
    row = settled_row(raw, settle)
    check_chains(row)
    f = row.view("<f4")
    return {
        "index": index,
        "attack_coeff": float(f[0]),
        "decay_coeff": float(f[1]),
        "release_coeff": float(f[2]),
        "attack_bits": int(row[0]),
        "decay_bits": int(row[1]),
    }


def sweep(ns: argparse.Namespace) -> int:  # pragma: no cover - needs local firmware images
    work = Path(ns.workdir)
    work.mkdir(parents=True, exist_ok=True)
    rows = [run_index(ns, i, work, ns.passes, ns.settle) for i in INDEX_RANGE]
    with Path(ns.out).open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow(
                {
                    **r,
                    "attack_coeff": f"{r['attack_coeff']:.9g}",
                    "decay_coeff": f"{r['decay_coeff']:.9g}",
                    "release_coeff": f"{r['release_coeff']:.9g}",
                    "attack_bits": f"{r['attack_bits']:#010x}",
                    "decay_bits": f"{r['decay_bits']:#010x}",
                }
            )
    return 0



#!/usr/bin/env python3
"""Rust data files of the firmware stage `0x1257B2` (`crates/nord-core/src/synth/fw_stage3*.rs`).

    python tools/synth_filter_t3_golden.py tables > crates/nord-core/src/synth/fw_stage3_tables.rs
    python tools/synth_filter_t3_golden.py golden > \
        crates/nord-core/src/synth/tests_fw_stage3_golden.rs
    cargo fmt -p nord-core

`tables` turns the derived CSV `docs/research/data/synth-filter-t3-tables.csv` (float32 words of
the ORG core 2 image, no code) into `u32` arrays. `golden` runs the bit-exact model
`synth_filter_t3.py` (equal to the SHARC oracle, 1840 of 1840 words) over fixed rows and a fixed
input, so the Rust float32 stage is compared with the model on identical inputs.
"""

from __future__ import annotations

import math
import struct
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
import synth_filter_t3 as t3

# Golden rows: (cutoff word `R`, position word `W`): low to high cutoff and resonance position.
ROWS = (
    (0x3E99999A, 0x04000000),
    (0x3DF5C28F, 0x28800000),
    (0x3F4CCCCD, 0x40000000),
    (0x3F8CCCCD, 0x64000000),
    (0x3D4CCCCD, 0x7E400000),
)
SAMPLES = 64

TABLES_TEST = """#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_have_the_documented_shape() {
        assert_eq!(f32::from_bits(T1[0]), 0.0, "g starts at zero");
        assert_eq!(f32::from_bits(T2[0]), 2.0, "damping starts at 2");
        assert!(f32::from_bits(T0[128]) > 1.9, "resonance map saturates near 2");
    }
}
"""

GOLDEN_TESTS = """
fn coefs(r: usize) -> Stage3Coefs {
    let (w_r, w_pos) = ROWS[r];
    Stage3Coefs::new(f32::from_bits(w_r), TablePos::from_word(w_pos))
}

#[test]
fn coefficient_words_match_the_model() {
    for r in 0..ROWS.len() {
        let co = coefs(r);
        let got = [co.h, co.g, co.v, co.kc, co.x1x2, co.x2];
        for (k, &g) in got.iter().enumerate() {
            let w = f32::from_bits(COEFS[6 * r + k]);
            assert!(
                (g - w).abs() <= 2e-6 * w.abs() + 1e-9,
                "row {r} coef {k}: {g} vs {w}"
            );
        }
    }
}

#[test]
fn output_matches_the_model_words() {
    for r in 0..ROWS.len() {
        let co = coefs(r);
        let mut f = FwStage3::default();
        let mut w = 0.0f32;
        for n in 0..N {
            let y = f.process(f32::from_bits(INPUT[n]), &co);
            w = w.max((y - f32::from_bits(OUTPUT[r * N + n])).abs());
        }
        assert!(w < 2e-5, "row {r}: worst deviation {w}");
    }
}
"""


def f2u(x: float) -> int:
    """Float32 bit pattern of `x`."""
    return struct.unpack("<I", struct.pack("<f", x))[0]


def input_words() -> list[int]:
    """Fixed test input: a decaying two tone burst (words)."""
    return [
        f2u(0.8 * math.sin(0.21 * n) + 0.4 * math.sin(1.7 * n + 1.0)) if n < 40 else 0
        for n in range(SAMPLES)
    ]


def fmt_words(name: str, words: list[int], per_line: int = 8) -> str:
    """A `pub(super) const NAME: [u32; N]` item."""
    rows = "".join(
        "    " + ", ".join(f"{w:#010x}" for w in words[i : i + per_line]) + ",\n"
        for i in range(0, len(words), per_line)
    )
    return f"pub(super) const {name}: [u32; {len(words)}] = [\n{rows}];\n"


def tables() -> str:
    """The Rust table file."""
    out = (
        "//! Derived tables of the stage `0x1257B2` (raw filter type 3): `T0`\n"
        "//! (resonance position, `DM(0xB0A9F)`), `T1` (`DM(0xB0C0D)`) and `T2`\n"
        "//! (`DM(0xB0C8E)`), 129 words each.\n//!\n"
        "//! Generated by `python tools/synth_filter_t3_golden.py tables` from\n"
        "//! `docs/research/data/synth-filter-t3-tables.csv` (float32 words of the ORG core 2\n"
        "//! image, derived values only). VERIFIED: the model that uses them equals the oracle\n"
        "//! word for word (`docs/research/synth-filter-t3.md`).\n\n"
    )
    for name, col in zip(("T0", "T1", "T2"), t3.TABLES, strict=True):
        out += fmt_words(name, col) + "\n"
    return out + TABLES_TEST


def golden() -> str:
    """The Rust golden test file."""
    xs = input_words()
    out = (
        "//! Firmware parity of the stage `0x1257B2` (`fw_stage3.rs`).\n//!\n"
        "//! Generated by `python tools/synth_filter_t3_golden.py golden` from the bit-exact\n"
        "//! model `tools/synth_filter_t3.py` (equal to the SHARC oracle). Do not edit by hand.\n\n"
        "use super::fw_filter::TablePos;\n"
        "use super::fw_stage3::{FwStage3, Stage3Coefs};\n\n"
    )
    out += f"const N: usize = {SAMPLES};\n"
    out += f"pub(super) const ROWS: [(u32, u32); {len(ROWS)}] = [\n"
    for a, b in ROWS:
        out += f"    ({a:#010x}, {b:#010x}),\n"
    out += "];\n"
    out += fmt_words("INPUT", xs)
    coef_words: list[int] = []
    outs: list[int] = []
    for w_r, w_pos in ROWS:
        ln = t3.Lane()
        seq: list[int] = []
        words: dict[str, int] = {}
        for i in range(0, SAMPLES, 4):
            o4, words = t3.process(ln, w_r, w_pos, xs[i : i + 4])
            seq += o4
        coef_words += [words[k] for k in t3.COEF_KEYS]
        outs += seq
    out += fmt_words("COEFS", coef_words)
    out += fmt_words("OUTPUT", outs)
    return out + GOLDEN_TESTS


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if args[:1] == ["tables"]:
        sys.stdout.write(tables())
    elif args[:1] == ["golden"]:
        sys.stdout.write(golden())
    else:
        sys.stderr.write(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
